# 대상 지역 한곳 관리 — 전국 확대 때는 이 파일만 바꾸면(또는 REGIONS=all 환경변수) 모든 build_*.py가 따라감.
#   REGIONS=all python3 build_xxx.py ...        → 17개 시도 전부
#   REGIONS=11,41,26 python3 build_xxx.py ...    → 법정동 시도코드로 직접 지정
# 코드 두 가지: bjd = 법정동코드 앞 2자리(실거래가·건물자료·도로명주소), sgis = 통계청 행정구역코드 앞 2자리(sub.json 동 경계·인구 격자)
import os
SIDO = [  # (bjd, sgis, 정식 이름, 줄임말)
    ('11', '11', '서울특별시', '서울'), ('26', '21', '부산광역시', '부산'), ('27', '22', '대구광역시', '대구'),
    ('28', '23', '인천광역시', '인천'), ('29', '24', '광주광역시', '광주'), ('30', '25', '대전광역시', '대전'),
    ('31', '26', '울산광역시', '울산'), ('36', '29', '세종특별자치시', '세종'), ('41', '31', '경기도', '경기'),
    ('51', '32', '강원특별자치도', '강원'), ('43', '33', '충청북도', '충북'), ('44', '34', '충청남도', '충남'),
    ('52', '35', '전북특별자치도', '전북'), ('46', '36', '전라남도', '전남'), ('47', '37', '경상북도', '경북'),
    ('48', '38', '경상남도', '경남'), ('50', '39', '제주특별자치도', '제주'),
]
DEFAULT = ('11', '28', '30', '36', '41', '43', '44', '52')  # 2026-11 현재: 서울·인천·대전·세종·경기·충북·충남·전북
_env = os.environ.get('REGIONS', '').strip()
ACTIVE = tuple(s[0] for s in SIDO) if _env == 'all' else tuple(x.strip() for x in _env.split(',') if x.strip()) if _env else DEFAULT
ON = [s for s in SIDO if s[0] in ACTIVE]
BJD = tuple(s[0] for s in ON)             # ('11','28',...)
SGIS = tuple(s[1] for s in ON)            # ('11','23',...)
NAME = {s[0]: s[2] for s in SIDO}         # '11' → '서울특별시' (전체: 이름 찾기는 대상 밖 코드가 와도 죽지 않게)
FULL = {s[2] for s in ON}                 # {'서울특별시',...}
SHORT = [s[3] for s in ON]                # ['서울','인천',...]
SHORT2BJD = {s[3]: s[0] for s in ON}
LABEL = '·'.join(SHORT) if len(ON) < len(SIDO) else '전국'
